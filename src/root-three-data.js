export function rootThreeNarration(lesson) {
  return [
    lesson.sageOpen,
    ...lesson.story.map((block) => {
      if (block.type === 'dialogue') return `${block.speaker} says, “${block.text}”`;
      if (block.type === 'sage') return `Sage says, “${block.text}”`;
      return block.text;
    }),
  ].join('\n\n');
}
